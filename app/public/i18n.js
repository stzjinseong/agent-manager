function _t(src, vars) {
  let s = LANG === 'ko' ? src : DICTS[LANG]?.[src];
  if (s == null) s = src;
  if (typeof s === 'function') return s(vars || {});
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

// data-i18n 요소: 처음 본 원문(한국어)을 기억해 두고 그 원문으로 번역한다 — 언어를 몇 번 바꿔도 원문에서 다시 옮긴다
function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n], [data-i18n-attr]')) {
    const src = (el._i18n ||= { attrs: {} });
    if (el.hasAttribute('data-i18n')) {
      src.html ??= el.innerHTML.trim();
      const v = _t(src.html);
      if (el.innerHTML !== v) el.innerHTML = v;
    }
    for (const a of (el.dataset.i18nAttr || '').split(',').map((x) => x.trim()).filter(Boolean)) {
      if (!(a in src.attrs)) src.attrs[a] = el.getAttribute(a);
      if (src.attrs[a] != null) el.setAttribute(a, _t(src.attrs[a]));
    }
  }
  document.documentElement.lang = LANG;
}

// 언어 바꾸기 — 이미 그 언어면 아무것도 하지 않는다. 화면의 동적 부분은 app.js 가 'langchange' 를 받아 다시 그린다
function setLang(l) {
  if (l === LANG || !LANGS.some(([k]) => k === l)) return false;
  LANG = l;
  try { localStorage.setItem(LANG_KEY, l); } catch {}
  applyI18n();
  document.dispatchEvent(new Event('langchange'));
  return true;
}
